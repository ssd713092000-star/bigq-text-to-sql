"""Generate infra/gcp/sql/cloudsql_init.sql: the same DDL the migrate job applies, as one psql file.

    uv run --package analyst-api python scripts/gen_cloudsql_sql.py

Built from the installed code, so it always matches:
  - app tables:        `alembic upgrade head --sql` (offline mode)
  - checkpoint tables: langgraph-checkpoint-postgres MIGRATIONS, plus the checkpoint_migrations rows
                       that make AsyncPostgresSaver.setup() treat them as already applied.
Re-run after adding an Alembic migration or upgrading langgraph-checkpoint-postgres.
"""

from __future__ import annotations

import io
import sys
from importlib.metadata import version
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "api"))

from alembic import command  # noqa: E402
from alembic.config import Config  # noqa: E402
from alembic.script import ScriptDirectory  # noqa: E402
from langgraph.checkpoint.postgres.base import BasePostgresSaver  # noqa: E402

from app.config import APP_SCHEMA, CHECKPOINT_SCHEMA, MEM0_SCHEMA  # noqa: E402

OUT = ROOT / "infra" / "gcp" / "sql" / "cloudsql_init.sql"


def alembic_sql() -> tuple[str, str]:
    buf = io.StringIO()
    cfg = Config(str(ROOT / "api" / "alembic.ini"), output_buffer=buf)
    cfg.set_main_option("script_location", str(ROOT / "api" / "migrations"))
    cfg.attributes["skip_logging"] = True
    command.upgrade(cfg, "head", sql=True)
    head = ScriptDirectory.from_config(cfg).get_current_head()
    return buf.getvalue(), head or "none"


def checkpoint_sql() -> str:
    # setup() records every applied version, v0 included, in checkpoint_migrations (created by v0)
    parts = []
    for v, stmt in enumerate(BasePostgresSaver.MIGRATIONS):
        parts.append(f"-- langgraph migration v{v}\n{stmt.strip().rstrip(';')};\n"
                     f"INSERT INTO checkpoint_migrations (v) VALUES ({v}) ON CONFLICT DO NOTHING;")
    return "\n\n".join(parts)


def main() -> None:
    app_sql, head = alembic_sql()
    lg_version = version("langgraph-checkpoint-postgres")
    text = f"""-- ============================================================================================
-- Cloud SQL (PostgreSQL) schema for the Text-to-SQL Analyst.  GENERATED by scripts/gen_cloudsql_sql.py
--   alembic head:                   {head}
--   langgraph-checkpoint-postgres:  {lg_version}
--
-- Preferred: let the Cloud Run job `analyst-migrate` (python -m app.migrate) apply this; it is idempotent.
-- Manual:    psql "host=127.0.0.1 port=5432 dbname=analyst user=analyst" -f cloudsql_init.sql
--            through the Cloud SQL Auth Proxy (see docs/cloudsql.md). Run with psql's default autocommit:
--            the checkpoint indexes use CREATE INDEX CONCURRENTLY, which can't run inside a transaction.
-- ============================================================================================

\\set ON_ERROR_STOP on

-- 1. extension + schemas ------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS vector;
CREATE SCHEMA IF NOT EXISTS {APP_SCHEMA};
CREATE SCHEMA IF NOT EXISTS {CHECKPOINT_SCHEMA};
CREATE SCHEMA IF NOT EXISTS {MEM0_SCHEMA};

-- 2. app tables (Alembic) --------------------------------------------------------------------------
SET search_path TO {APP_SCHEMA}, public;

{app_sql.strip()}

-- 3. LangGraph checkpointer tables (used by create_agent's AsyncPostgresSaver) ---------------------
SET search_path TO {CHECKPOINT_SCHEMA}, public;

{checkpoint_sql()}

RESET search_path;
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}  (alembic {head}, langgraph-checkpoint-postgres {lg_version})")


if __name__ == "__main__":
    main()
